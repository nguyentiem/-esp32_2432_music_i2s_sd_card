#!/usr/bin/env python3
"""Generate the checked-in NFC Vietnamese bitmap font; requires Pillow/DejaVu Sans."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf', 14)
points = list(range(32, 127)) + list(range(160, 512)) + list(range(0x1ea0, 0x1efa))
lines = ['// Generated by tools/make_font.py; DejaVu license: third_party/fonts/LICENSE',
         '#pragma once', '#include <cstdint>',
         'struct Glyph { uint16_t code; uint8_t advance; uint16_t rows[20]; };',
         'static const Glyph font[] = {']
for code in points:
    im = Image.new('1', (16, 20))
    ImageDraw.Draw(im).text((0, 0), chr(code), font=font, fill=1)
    rows = [sum((1 << (15 - x)) for x in range(16) if im.getpixel((x, y))) for y in range(20)]
    advance = min(16, max(1, round(font.getlength(chr(code)))))
    lines.append('{%d,%d,{%s}},' % (code, advance, ','.join('0x%04x' % r for r in rows)))
lines.append('};')
Path(__file__).resolve().parents[1].joinpath('main/font.h').write_text('\n'.join(lines) + '\n')
